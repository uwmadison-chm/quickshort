// Compile a directory of redirect files (same format as the Flask app's
// REDIRECTS_PATH: file name = key, contents = target URL) into
// src/redirects.generated.ts. Fails on anything that would never be served.
//
// Usage: node scripts/build-redirects.ts [redirects-dir]
// Default dir: $REDIRECTS_DIR, else ./redirects

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const KEY_RE = /^[a-z0-9]+$/;

export function loadRedirects(dir: string): { redirects: Record<string, string>; errors: string[] } {
  const redirects: Record<string, string> = {};
  const errors: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.') || name.startsWith('_') || name.endsWith('.md')) continue;
    const file = join(dir, name);
    if (!statSync(file).isFile()) continue;
    if (!KEY_RE.test(name)) {
      errors.push(`${name}: key must be lowercase letters and digits only`);
      continue;
    }
    const target = readFileSync(file, 'utf8').trim();
    let parsed: URL;
    try {
      parsed = new URL(target);
    } catch {
      errors.push(`${name}: not a valid URL: ${JSON.stringify(target)}`);
      continue;
    }
    if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
      errors.push(`${name}: URL must be http or https: ${target}`);
      continue;
    }
    redirects[name] = target;
  }
  return { redirects, errors };
}

if (import.meta.main) {
  const dir = resolve(process.argv[2] ?? process.env.REDIRECTS_DIR ?? 'redirects');
  const { redirects, errors } = loadRedirects(dir);
  if (errors.length) {
    for (const e of errors) console.error(`error: ${e}`);
    process.exit(1);
  }
  const out = resolve(import.meta.dirname, '../src/redirects.generated.ts');
  writeFileSync(
    out,
    '// Generated by scripts/build-redirects.ts. Do not edit.\n' +
      `const redirects: Readonly<Record<string, string>> = ${JSON.stringify(redirects, null, 2)};\n` +
      'export default redirects;\n',
  );
  console.log(`Wrote ${Object.keys(redirects).length} redirects from ${dir} to ${out}`);
}
